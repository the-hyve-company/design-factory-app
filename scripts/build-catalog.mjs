#!/usr/bin/env node
// build-catalog.mjs — generates docs/catalog.md from the disk.
//
// Everything forkable in the repo (skills, examples, templates, builtin
// rules) in one page, with counts derived from the tree — never typed by
// hand. Output is deterministic (no timestamps) so re-runs are diff-clean.
//
//   npm run catalog:build
//
// Sources scanned:
//   skills/{slug}/SKILL.md        → name, trigger, description, license file
//   examples/*.html               → shipped artifacts
//   templates/{slug}/             → composition templates
//   src/data/rules-taxonomy.ts    → builtin rules + categories (regex parse)

import { readFileSync, readdirSync, existsSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();

function parseFrontmatter(raw) {
  const fm = raw.match(/^---\s*\n([\s\S]*?)\n---/)?.[1] ?? "";
  const pick = (key) => {
    const m = fm.match(new RegExp(`^${key}\\s*:\\s*(.+)$`, "m"));
    return m ? m[1].trim().replace(/^["'](.*)["']$/, "$1") : null;
  };
  return { name: pick("name"), trigger: pick("trigger"), description: pick("description") };
}

function skillLicenseLabel(dir) {
  for (const f of ["LICENSE", "LICENSE.txt", "LICENSE.md"]) {
    const p = join(dir, f);
    if (existsSync(p)) {
      const head = readFileSync(p, "utf8").slice(0, 200);
      if (/MIT License/i.test(head)) return "MIT (preserved)";
      if (/Apache License/i.test(head)) return "Apache-2.0 (preserved)";
      return "upstream license (preserved)";
    }
  }
  if (existsSync(join(dir, "NOTICE.md"))) return "provenance NOTICE.md";
  return "—";
}

function collectSkills() {
  const base = join(root, "skills");
  if (!existsSync(base)) return [];
  return readdirSync(base, { withFileTypes: true })
    .filter((e) => e.isDirectory() && !e.name.startsWith("."))
    .map((e) => {
      const dir = join(base, e.name);
      const manifest = join(dir, "SKILL.md");
      if (!existsSync(manifest)) return null;
      const { name, trigger, description } = parseFrontmatter(readFileSync(manifest, "utf8"));
      const firstSentence = (description ?? "").split(/(?<=\.)\s/)[0].slice(0, 140);
      return {
        slug: e.name,
        name: name ?? e.name,
        trigger: trigger ?? `/${e.name}`,
        description: firstSentence,
        license: skillLicenseLabel(dir),
      };
    })
    .filter(Boolean)
    .sort((a, b) => a.slug.localeCompare(b.slug));
}

function collectExamples() {
  const base = join(root, "examples");
  if (!existsSync(base)) return [];
  return readdirSync(base)
    .filter((f) => f.endsWith(".html"))
    .sort();
}

function collectTemplates() {
  const base = join(root, "templates");
  if (!existsSync(base)) return [];
  return readdirSync(base, { withFileTypes: true })
    .filter((e) => e.isDirectory() && !e.name.startsWith("."))
    .map((e) => e.name)
    .sort();
}

function collectRules() {
  const src = readFileSync(join(root, "src", "data", "rules-taxonomy.ts"), "utf8");
  const rulesBlock = src.slice(src.indexOf("DEFAULT_BUILTIN_RULES"));
  const categories = [...rulesBlock.matchAll(/category:\s*"([^"]+)"/g)].map((m) => m[1]);
  const byCategory = new Map();
  for (const c of categories) byCategory.set(c, (byCategory.get(c) ?? 0) + 1);
  return { total: categories.length, byCategory };
}

const skills = collectSkills();
const examples = collectExamples();
const templates = collectTemplates();
const rules = collectRules();

const lines = [];
lines.push("# Catalog");
lines.push("");
lines.push("<!-- AUTO-GENERATED by scripts/build-catalog.mjs — do not edit by hand.");
lines.push("     Regenerate with: npm run catalog:build -->");
lines.push("");
lines.push("Everything forkable that ships in this repository, counted from the");
lines.push("tree itself. Licensing details for bundled skills live in the root");
lines.push("[NOTICE](../NOTICE) and in each skill folder.");
lines.push("");
lines.push(`## Skills (${skills.length})`);
lines.push("");
lines.push("| Trigger | Folder | License | What it does |");
lines.push("| --- | --- | --- | --- |");
for (const s of skills) {
  lines.push(
    `| \`${s.trigger}\` | \`skills/${s.slug}/\` | ${s.license} | ${s.description.replace(/\|/g, "\\|")} |`,
  );
}
lines.push("");
lines.push(`## Examples (${examples.length})`);
lines.push("");
lines.push("Finished HTML artifacts under `examples/` — open in a browser or remix");
lines.push("into a project. See [examples/README.md](../examples/README.md).");
lines.push("");
for (const f of examples) lines.push(`- \`examples/${f}\``);
lines.push("");
lines.push(`## Templates (${templates.length})`);
lines.push("");
for (const t of templates) lines.push(`- \`templates/${t}/\``);
lines.push("");
lines.push(`## Builtin rules (${rules.total})`);
lines.push("");
lines.push("Defined in `src/data/rules-taxonomy.ts`, grouped by category:");
lines.push("");
lines.push("| Category | Rules |");
lines.push("| --- | --- |");
for (const [cat, count] of rules.byCategory) lines.push(`| ${cat} | ${count} |`);
lines.push("");
lines.push("## Design systems (0 — by decision)");
lines.push("");
lines.push("`design-systems/` ships empty for IP safety (#101): create or import");
lines.push("your own through the app. CI enforces that it stays empty.");
lines.push("");

writeFileSync(join(root, "docs", "catalog.md"), lines.join("\n"));
console.log(
  `catalog: ${skills.length} skills · ${examples.length} examples · ` +
    `${templates.length} templates · ${rules.total} rules → docs/catalog.md`,
);
